def seed_teachers_if_empty() -> int:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        existing_count = db.query(Teacher).count()
        if existing_count > 0:
            return 0
        for idx, data in enumerate(INITIAL_TEACHERS, start=1):
            db.add(Teacher(**data, sort_order=idx * 10))
        db.commit()
        return len(INITIAL_TEACHERS)
    finally:
        db.close()


if __name__ == "__main__":
    inserted = seed_teachers_if_empty()
    print(f"Seeded teachers: {inserted}")
