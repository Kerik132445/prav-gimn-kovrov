def seed_menu_data() -> int:
    db = SessionLocal()
    try:
        if db.query(MenuItem).count() > 0 or db.query(MenuDayMeal).count() > 0:
            print("Menu data already exists in database; skipping seed.")
            return 0

        created_items = 0
        created_meals = 0

        for age_group in ("spassky", "pokrovsky"):
            for week_number, days_map in INITIAL_WEEK_DATA.items():
                for day_of_week, meals_map in days_map.items():
                    for meal_type, meal_data in meals_map.items():
                        db.add(
                            MenuDayMeal(
                                age_group=age_group,
                                week_number=week_number,
                                day_of_week=day_of_week,
                                meal_type=meal_type,
                                price=meal_data["price"],
                                kbju=meal_data["kbju"],
                            )
                        )
                        created_meals += 1

                        for idx, (dish_name, dish_weight) in enumerate(meal_data["dishes"], start=1):
                            db.add(
                                MenuItem(
                                    age_group=age_group,
                                    week_number=week_number,
                                    day_of_week=day_of_week,
                                    meal_type=meal_type,
                                    name=dish_name,
                                    weight=dish_weight,
                                    sort_order=idx * 10,
                                )
                            )
                            created_items += 1

        db.commit()
        print(f"Seeded menu items: {created_items}, meal summaries: {created_meals}")
        return created_items
    finally:
        db.close()


if __name__ == "__main__":
    seed_menu_data()
