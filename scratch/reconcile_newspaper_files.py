items = []
for f in files:
    if not f.endswith('.pdf'):
        continue
    sz = os.path.getsize(os.path.join(pdf_dir, f)) / (1024 * 1024)
    if 'витражи' in f.lower():
        items.append({
            'file': f,
            'year': '2023',
            'num_int': 999,
            'num_label': 'Спецвыпуск',
            'title': '«Сретенские витражи»',
            'season': 'Литературно-исторический альманах',
            'desc': 'Специальный выпуск: летопись гимназии, воспоминания наставников, стихи и эссе воспитанников.',
            'size': f"{sz:.1f} МБ",
            'is_special': True
        })
    elif f.startswith('№') and '-' in f:
        # e.g. №3-2015.pdf
        num_str, yr_part = f.replace('№', '').split('-')
        yr = yr_part.replace('.pdf', '')
        num = int(num_str)
        theme, desc = special_names.get((yr, num), (f"Выпуск № {num}", "События школьной жизни, паломнические поездки и творчество."))
        items.append({
            'file': f,
            'year': yr,
            'num_int': num,
            'num_label': f"№ {num}",
            'title': f"«Доброе слово» № {num} ({yr})",
            'season': theme,
            'desc': desc,
            'size': f"{sz:.1f} МБ",
            'is_special': False
        })

items.sort(key=lambda x: (int(x['year']), x['num_int']), reverse=True)
print(f"Cataloged {len(items)} PDF items matching user's exact files.")

# Also create duplicate copies with Latin filenames Dobroe_slovo_YYYY_NN.pdf
# so that both Russian and Latin filenames work seamlessly on any server!
for it in items:
    orig = it['file']
    orig_path = os.path.join(pdf_dir, orig)
    if 'витражи' in orig.lower():
        alt_name = "Sretenskie_vitrazhi_2023.pdf"
    else:
        alt_name = f"Dobroe_slovo_{it['year']}_{it['num_int']:02d}.pdf"
    alt_path = os.path.join(pdf_dir, alt_name)
    if not os.path.exists(alt_path):
        import shutil
        shutil.copyfile(orig_path, alt_path)
        print(f"Created alt copy: {alt_name}")

